import { mkdtempSync, mkdirSync, realpathSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ReviewStore } from "./review.js";

/** An isolated, repeatable review scenario. Nothing is added to the real session. */
export function createDemoStore() {
  const directory = realpathSync(mkdtempSync(join(tmpdir(), "pi-annotate-demo-")));
  const workspace = join(directory, "workspace");
  const source = join(workspace, "src");
  const run = join(workspace, "runs", "exp-01");
  const notes = join(workspace, "notes");
  const shared = join(directory, "shared-output"); // captured edits outside the Pi cwd
  for (const path of [source, run, notes, shared]) mkdirSync(path, { recursive: true });
  const store = new ReviewStore(workspace, join(directory, "review-state.json"), "demo-session");
  const captured = (id: string, path: string, content: string) => {
    store.begin(id, path);
    writeFileSync(path, content);
    store.end(id, false);
  };

  store.nextRequest();
  captured("earlier", join(source, "legacy.md"), "# Earlier request\n\nThis change belongs to the previous request.\n");
  store.nextRequest();
  const report = join(source, "report.md");
  writeFileSync(report, "# Experiment report\n\nStatus: pending.\n");
  captured("report", report, "# Experiment report\n\nStatus: complete.\n\nThe script generated results in runs/exp-01/.\n");
  captured("config", join(source, "config.json"), '{"run":"exp-01","threshold":0.75}\n');
  const script = join(run, "generate.py");
  captured("script", script, 'from pathlib import Path\n\n# Imagine running this through bash; its outputs are not Pi write/edit calls.\nPath(__file__).with_name("results.json").write_text("{\\"accuracy\\":0.91}\\n")\n');
  captured("shared-a", join(shared, "summary.md"), "# Shared summary\n\nCreated outside the Pi cwd.\n");
  captured("shared-b", join(shared, "checks.txt"), "passed: 5\nfailed: 0\n");
  // Intentionally bypass capture, like results generated by bash or another process.
  writeFileSync(join(run, "results.json"), '{"accuracy":0.91,"samples":120}\n');
  writeFileSync(join(run, "metrics.csv"), "metric,value\naccuracy,0.91\nlatency_ms,17\n");
  const context = join(notes, "context.md");
  writeFileSync(context, "# Context\n\nOpened for review, but not edited by the agent.\n");
  store.addFile(context);
  store.response("demo-answer", "I updated the report and generator. Please review the output under `runs/exp-01/`.");
  return { directory, workspace, store, script, report, run, context, shared };
}
