import { mkdtempSync, writeFileSync, readFileSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { ReviewStore } from '../review.ts';
import { startAnnotationServer } from '../server.ts';
import { registerReview } from '../review-extension.ts';

const directory = mkdtempSync(join(tmpdir(), 'pi-review-'));
try {
  const path = join(directory, 'doc.md'), state = join(directory, 'state.json');
  const store = new ReviewStore(directory, state, 'test-session');
  writeFileSync(path, '# Before\n');
  store.nextRequest(); store.begin('one', path); writeFileSync(path, '# After\n'); store.end('one', false);
  assert.equal(store.state.files[path].before.text, '# Before\n');
  assert.equal(store.list().files[0].latest, true);
  assert.equal(store.list().files[0].label, 'doc.md');
  store.nextRequest();
  assert.equal(store.list().files[0].latest, false);
  store.begin('two', path); writeFileSync(path, '# Current\n'); store.end('two', false);
  assert.equal(store.state.files[path].requestBefore.text, '# After\n');
  assert.match(store.document(path, 'session').patch, /-# Before/);
  assert.match(store.document(path, 'request').patch, /-# After/);
  store.begin('failed', path); store.end('failed', true);
  assert.equal(store.pending.size, 0);
  const annotation = { id: 'ann-1', type: 'comment', text: 'Make clearer', originalText: 'Current', range: { startOffset: 2, endOffset: 9, textPreview: 'Current' }, createdAt: Date.now() };
  store.draft({ path, markdown: '# Current\n', annotations: [annotation] });
  writeFileSync(path, '# External\n');
  assert.equal(store.document(path, 'session').plan, '# Current\n');
  assert.match(store.document(path, 'session').warning!, /New version/);
  assert.equal(store.document(path, 'session').stale, true);
  assert.match(store.diskComparison(path).patch!, /annotated snapshot/);
  assert.match(store.diskComparison(path).patch!, /\+# External/);
  assert.throws(() => store.diskComparison('/etc/passwd'));
  assert.match(store.feedback(), /file has changed/);
  assert.ok(!store.feedback().includes('Snapshot:'));
  assert.ok(!store.feedback().includes(store.state.drafts[path].version));
  assert.match(store.feedback(), /> Current/);
  const resumed = new ReviewStore(directory, state, 'test-session');
  assert.equal(resumed.state.drafts[path].annotations.length, 1);
  assert.throws(() => store.draft({ path: '/not-registered', markdown: '', annotations: [] }));
  assert.throws(() => store.draft({ path, markdown: '', annotations: [annotation] }));
  store.begin('external', path); writeFileSync(path, '# Pi again\n'); store.end('external', false);
  assert.equal(store.state.files[path].external, true);
  const fresh = join(directory, 'new.md'); store.begin('new', fresh); writeFileSync(fresh, 'new'); store.end('new', false);
  assert.equal(store.state.files[fresh].before.text, null);
  const binary = join(directory, 'binary'); store.begin('binary', binary); writeFileSync(binary, Buffer.from([0, 1])); store.end('binary', false);
  assert.match(store.state.files[binary].after.error!, /Binary/);
  assert.throws(() => store.document('/etc/passwd', 'session'));
  store.clearDrafts(); assert.equal(store.feedback(), '');
  const manual = join(directory, 'manual.md'); writeFileSync(manual, '# Manual');
  store.addFile(manual);
  assert.equal(store.document(manual, 'session').patch, null);
  assert.equal(store.document(manual, 'session').recorded, false);
  const json = join(directory, 'result.json'); writeFileSync(json, '{"accuracy":0.91,"hint":"<script>"}');
  store.addFile(json);
  const highlighted = store.document(json, 'session');
  assert.match(highlighted.planHtml, /hljs-attr/);
  assert.ok(!highlighted.planHtml.includes('<script>'));
  assert.equal(highlighted.patch, null);
  const tex = join(directory, 'paper.tex');
  const source = '\\section{Introduction}\nA long line ' + 'x'.repeat(180) + '\n\n';
  writeFileSync(tex, source); store.addFile(tex);
  const latexDocument = store.document(tex, 'session');
  assert.equal(latexDocument.plan, source);
  assert.match(latexDocument.planHtml, /hljs-/);
  assert.equal(latexDocument.patch, null);
  const java = join(directory, 'Example.java');
  writeFileSync(java, 'public class Example {}\n'); store.addFile(java);
  assert.match(store.document(java, 'session').planHtml, /hljs-keyword/);
  store.begin('manual-edit', manual); writeFileSync(manual, '# Updated'); store.end('manual-edit', false);
  assert.match(store.document(manual, 'session').patch!, /-# Manual/);
  assert.equal(store.document(manual, 'session').recorded, true);
  const message = store.response('entry-1', '# Current\n')!;
  store.draft({ path: message, markdown: '# Current\n', annotations: [annotation] });
  assert.equal(store.document(message, 'request').kind, 'response');
  assert.equal(store.document(message, 'request').patch, null);
  assert.match(store.feedback(), /About your response \(message entry-1\)/);
  assert.ok(!store.feedback().includes('Snapshot:'));
  assert.ok(!store.feedback().includes(store.state.drafts[message].version));
  assert.ok(!store.feedback().includes('Line 1'));
  assert.throws(() => store.draft({ path: message, markdown: 'wrong', annotations: [] }));
  store.nextRequest(); store.response('entry-2', 'Another answer');
  assert.equal(store.list().responses.length, 2);
  assert.equal(store.document(message, 'request').plan, '# Current\n');
  assert.equal(store.list().responses.find(r => r.path === message)!.latest, false);
  store.clearDrafts();
  assert.equal(store.list().responses.length, 1);
  // A page can still annotate a response that was open before a newer one arrived.
  store.draft({ path: message, markdown: '# Current\n', annotations: [annotation] });
  assert.equal(store.list().responses.length, 2);
  assert.equal(new ReviewStore(directory, state, 'test-session').document(message, 'session').kind, 'response');
  store.clearDrafts();
  console.log('PASS snapshots, scopes, creations, failed calls, external changes, frozen drafts, persistence, validation');

  const calls: string[] = [];
  const server = await startAnnotationServer({ markdown: '', renderedHtml: '', htmlContent: '__ANNOTATE_DATA__', mode: 'annotate', workspace: (route) => { calls.push(route); return { ok: true }; } });
  try {
    const html = await (await fetch(server.url)).text();
    const token = html.match(/"sessionToken":"([^"]+)"/)![1];
    assert.match(html, /"workspace":true/);
    assert.equal((await fetch(server.url + '/api/review/list')).status, 403);
    assert.equal(calls.length, 0);
    const response = await fetch(server.url + '/api/review/list', { headers: { 'X-Annotation-Token': token } });
    assert.equal(response.status, 200); assert.deepEqual(calls, ['/api/review/list']);
  } finally { server.stop(); }
  console.log('PASS workspace API authentication');

  // Exercise actual extension wiring, including Done into a nonempty Pi editor.
  const hooks = new Map<string, Function>(); let url = '', editor = 'My own text';
  const pi = { on: (name: string, fn: Function) => hooks.set(name, fn), exec: async (_: string, args: string[]) => { url = args.at(-1)!; return { code: 0 }; } };
  const open = registerReview(pi as any, join(directory, 'storage'));
  const branch: any[] = [];
  const ctx = { cwd: directory, mode: 'tui', sessionManager: { getBranch: () => branch, getSessionId: () => 'test-' + Date.now(), getSessionFile: () => join(directory, 'session.jsonl') }, ui: { notify() {}, getEditorText: () => editor, setEditorText: (s: string) => { editor = s; } } };
  await hooks.get('session_start')!({}, ctx);
  try {
    hooks.get('message_start')!({ message: { role: 'user' } });
    hooks.get('tool_call')!({ toolName: 'edit', input: { path }, toolCallId: 'real' });
    writeFileSync(path, '# Current\n');
    hooks.get('tool_execution_end')!({ toolCallId: 'real', isError: false });
    branch.push({ type: 'message', id: 'user-1', message: { role: 'user', content: [] } });
    branch.push({ type: 'message', id: 'answer-1', message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'private' }, { type: 'text', text: '# Current\n' }] } });
    hooks.get('agent_settled')!({}, ctx);
    await open(ctx as any, { last: true });
    const html = await (await fetch(url)).text();
    assert.ok(!html.includes('/* __REVIEW_SCRIPT__ */'));
    assert.ok(html.includes('Rendered Markdown code fences/indented blocks'));
    assert.ok(html.includes("content.querySelectorAll('pre')"));
    assert.ok(html.includes('wrapButton.hidden = !rawSource && !renderedCode;'));
    assert.ok(html.includes("querySelectorAll('.review-code-frame')"));
    assert.ok(html.includes("localStorage.removeItem('pi-annotate-theme')"));
    assert.ok(html.includes("fetch('/api/settings'"));
    const clientScript = html.match(/<script>([\s\S]*?)<\/script>/)?.[1] ?? '';
    assert.doesNotThrow(() => new Function(clientScript));
    const token = html.match(/"sessionToken":"([^"]+)"/)![1];
    const headers = { 'X-Annotation-Token': token, 'Content-Type': 'application/json' };
    const list = await (await fetch(url + '/api/review/list', { headers })).json() as any;
    assert.equal(list.files.length, 1);
    assert.equal(list.target, 'message:answer-1');
    assert.equal(list.responses.length, 1);
    assert.equal(list.responses[0].latest, true);
    const answer = await (await fetch(url + '/api/review/document?path=message%3Aanswer-1', { headers })).json() as any;
    assert.equal(answer.plan, '# Current\n');
    assert.equal(answer.patch, null);
    await fetch(url + '/api/review/draft', { method: 'POST', headers, body: JSON.stringify({ path: 'message:answer-1', markdown: '# Current\n', annotations: [annotation] }) });
    await fetch(url + '/api/review/draft', { method: 'POST', headers, body: JSON.stringify({ path, markdown: '# Current\n', annotations: [annotation] }) });
    const preview = await (await fetch(url + '/api/review/preview', { headers })).json() as any;
    assert.equal(preview.editorHasText, true);
    assert.match(preview.feedback, /About your response/);
    assert.match(preview.feedback, /Make clearer/);
    assert.equal(editor, 'My own text'); // Preview neither clears notes nor writes into Pi's editor.
    assert.equal((await fetch(url + '/api/review/done', { method: 'POST', headers, body: '{}' })).status, 200);
    assert.ok(editor.startsWith('My own text\n\n## Annotation feedback'));
    assert.ok(editor.includes('Make clearer'));
    assert.ok(editor.includes('About your response (message answer-1)'));
    await open(ctx as any, { file: manual });
    const manualList = await (await fetch(url + '/api/review/list', { headers })).json() as any;
    assert.equal(manualList.target, realpathSync(manual));
    assert.equal(manualList.targetFolder, realpathSync(directory));
    const previous = editor;
    await fetch(url + '/api/review/done', { method: 'POST', headers, body: '{}' });
    assert.equal(editor, previous);
    await open(ctx as any, { file: directory });
    const folderList = await (await fetch(url + '/api/review/list', { headers })).json() as any;
    assert.equal(folderList.target, undefined);
    assert.equal(folderList.targetFolder, realpathSync(directory));
  } finally { hooks.get('session_shutdown')!(); }
  console.log('PASS extension lifecycle, capture, draft delivery, preserving editor, duplicate Done');
} finally { rmSync(directory, { recursive: true, force: true }); }
